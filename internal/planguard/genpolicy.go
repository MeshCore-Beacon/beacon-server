package planguard

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

// hopParam matches a statement that filters on a hop count parameter. Such a statement must also prove its
// rare and absent hops before it is admitted.
var hopParam = regexp.MustCompile(`hop_count\s*(\+\s*0\s*)?=\s*\$\d`)

// hopShapes are the extra shapes a statement with a hop parameter must cover.
var hopShapes = []string{"rare_hop", "absent_hop"}

const policyHeader = `// Copyright 2026 Beacon Contributors
// SPDX-License-Identifier: AGPL-3.0-or-later

// Code generated by the plan policy generator. DO NOT EDIT.

package planpolicy

// Cached lists class G statements: those admitted to the generic-plan class.
`

// GenPolicy returns gofmt'd source for db/planpolicy/cached_gen.go: the license header, the generated-code line,
// "package planpolicy", the Cached doc comment and `var Cached = map[string]bool{…}` with the admitted sqlc
// names sorted.
//
// A statement is admitted iff its plan is cached, it has a sqlc source and no pending, it is not in legacy, its
// entries' shapes cover every tag of its admission profile (plus rare_hop and absent_hop when its text filters on
// a hop parameter), and every entry of it runs generic and auto with no skip or degrade_to and is neither
// expect_fail nor known_issue. A pending cached statement is left out silently; any other cached statement that
// misses a rule is an error naming the statement and what is missing, never a silent drop.
func GenPolicy(c *Corpus, legacy map[string]bool) ([]byte, error) {
	var admitted []string
	var errs []error
	for _, name := range sortedKeys(c.Statements) {
		st := c.Statements[name]
		if st.Plan != "cached" || st.Pending != "" {
			continue
		}
		problems := c.admissionProblems(name, st, legacy)
		if len(problems) > 0 {
			errs = append(errs, fmt.Errorf("statement %s is plan cached but %s", name, strings.Join(problems, "; ")))
			continue
		}
		admitted = append(admitted, st.SQLC)
	}
	if len(errs) > 0 {
		return nil, errors.Join(errs...)
	}
	slices.Sort(admitted)
	admitted = slices.Compact(admitted)

	var b bytes.Buffer
	b.WriteString(policyHeader)
	if len(admitted) == 0 {
		b.WriteString("var Cached = map[string]bool{}\n")
	} else {
		b.WriteString("var Cached = map[string]bool{\n")
		for _, n := range admitted {
			fmt.Fprintf(&b, "\t%s: true,\n", strconv.Quote(n))
		}
		b.WriteString("}\n")
	}
	return format.Source(b.Bytes())
}

// admissionProblems lists why a non-pending cached statement cannot be admitted; empty means it can.
func (c *Corpus) admissionProblems(name string, st *Statement, legacy map[string]bool) []string {
	var out []string
	if st.SQLC == "" {
		return []string{"has no sqlc source (only sqlc statements are served)"}
	}
	if legacy[st.SQLC] {
		out = append(out, "is in planpolicy.Legacy")
	}
	want := append([]string(nil), c.AdmissionProfiles[st.Admission]...)
	if hopParam.MatchString(st.SQL) {
		want = append(want, hopShapes...)
	}
	have := map[string]bool{}
	n := 0
	for _, e := range c.Entries {
		if e.Stmt != name {
			continue
		}
		n++
		for _, s := range e.Shapes {
			have[s] = true
		}
		modes := c.ModesOf(e)
		for _, m := range []string{ModeGeneric, ModeAuto} {
			switch ov := e.Mode[m]; {
			case !slices.Contains(modes, m):
				out = append(out, fmt.Sprintf("entry %s does not run %s", e.ID, m))
			case ov != nil && ov.Skip != "":
				out = append(out, fmt.Sprintf("entry %s skips %s", e.ID, m))
			case ov != nil && ov.DegradeTo != nil:
				out = append(out, fmt.Sprintf("entry %s degrades %s", e.ID, m))
			}
		}
		if e.ExpectFail {
			out = append(out, fmt.Sprintf("entry %s is expect_fail", e.ID))
		}
		if e.KnownIssue != "" {
			out = append(out, fmt.Sprintf("entry %s has a known_issue", e.ID))
		}
	}
	if n == 0 {
		out = append(out, "has no entries")
	}
	var missing []string
	for _, s := range want {
		if !have[s] && !slices.Contains(missing, s) {
			missing = append(missing, s)
		}
	}
	if len(missing) > 0 {
		out = append(out, fmt.Sprintf("its entries' shapes miss %s (admission %s)", strings.Join(missing, ", "), st.Admission))
	}
	return out
}
