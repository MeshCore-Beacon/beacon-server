func repoSQLC(t *testing.T) map[string]string {
	t.Helper()
	sqlcText, err := planguard.LoadStatements("../../db/sqlc")
	if err != nil {
		t.Fatal(err)
	}
	return sqlcText
}

func genPolicyErr(t *testing.T, file string, legacy map[string]bool) error {
	t.Helper()
	c, err := planguard.LoadCorpus(os.DirFS("testdata/corpus"), file, repoSQLC(t))
	if err != nil {
		t.Fatalf("%s: %v", file, err)
	}
	_, err = planguard.GenPolicy(c, legacy)
	return err
}

func TestGenPolicyRejectsCachedWithoutAdversarialShapes(t *testing.T) {
	cases := []struct {
		file   string
		legacy map[string]bool
		want   []string // every fragment must appear in the error
	}{
		{"genpolicy_hop.yaml", nil, []string{"ListKnownRoutesGlobalHop", "rare_hop", "absent_hop"}},
		{"genpolicy_hop_skip.yaml", nil, []string{"ListKnownRoutesGlobalHop", "entry gh.rare skips generic", "entry gh.absent skips generic"}},
		{"genpolicy_region_no_stale.yaml", nil, []string{"ListKnownRoutesByIATA", "stale_region"}},
		{"genpolicy_legacy_pending.yaml", map[string]bool{"GetNodeByID": true}, []string{"GetNodeByID", "planpolicy.Legacy"}},
		{"genpolicy_refuse_mode_known_issue_generic.yaml", nil, []string{"GetNodeByID", "entry node.miss has a known_issue in generic"}},
		{"genpolicy_refuse_mode_known_issue_auto.yaml", nil, []string{"GetNodeByID", "entry node.miss has a known_issue in auto"}},
		{"genpolicy_refuse_entry_known_issue.yaml", nil, []string{"GetNodeByID", "entry node.miss has a known_issue"}},
		{"genpolicy_refuse_expect_fail.yaml", nil, []string{"GetNodeByID", "entry node.miss is expect_fail"}},
		{"genpolicy_refuse_degrade_to.yaml", nil, []string{"GetNodeByID", "entry node.miss degrades auto"}},
		{"genpolicy_refuse_no_generic.yaml", nil, []string{"GetNodeByID", "entry node.miss does not run generic"}},
		{"genpolicy_refuse_no_auto.yaml", nil, []string{"GetNodeByID", "entry node.miss does not run auto"}},
		{"genpolicy_refuse_skip_auto.yaml", nil, []string{"GetNodeByID", "entry node.miss skips auto"}},
		{"genpolicy_refuse_no_sqlc.yaml", nil, []string{"statement Frozen", "has no sqlc source"}},
		{"genpolicy_refuse_no_entries.yaml", nil, []string{"GetNodeByID", "has no entries"}},
	}
	for _, tc := range cases {
		t.Run(tc.file, func(t *testing.T) {
			err := genPolicyErr(t, tc.file, tc.legacy)
			if err == nil {
				t.Fatal("want an error")
			}
			for _, w := range tc.want {
				if !strings.Contains(err.Error(), w) {
					t.Errorf("err = %v, want it to contain %q", err, w)
				}
			}
		})
	}

	// The same corpus with GetNodeByID out of Legacy: GetNodeByID is admitted and the pending cached statement is
	// left out without an error.
	c, err := planguard.LoadCorpus(os.DirFS("testdata/corpus"), "genpolicy_legacy_pending.yaml", repoSQLC(t))
	if err != nil {
		t.Fatal(err)
	}
	src, err := planguard.GenPolicy(c, nil)
	if err != nil {
		t.Fatalf("GenPolicy: %v", err)
	}
	if !bytes.Contains(src, []byte(`"GetNodeByID": true`)) || bytes.Contains(src, []byte("NotMergedYet")) {
		t.Errorf("source:\n%s\nwant GetNodeByID admitted and the pending statement left out", src)
	}
}

func TestGenPolicyEmptyCached(t *testing.T) {
	c, err := planguard.LoadCorpus(mapFS(map[string]string{"c.yaml": "statements:\n  C: {sqlc: C, plan: custom}\n"}), "c.yaml", testSQLC)
	if err != nil {
		t.Fatal(err)
	}
	src, err := planguard.GenPolicy(c, nil)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Contains(src, []byte("var Cached = map[string]bool{}\n")) {
		t.Errorf("source:\n%s\nwant an empty Cached", src)
	}
}

func TestGenPolicyMatchesCorpus(t *testing.T) {
	c, err := planguard.LoadCorpus(pgdata.Files, "corpus.yaml", repoSQLC(t))
	if err != nil {
		t.Fatal(err)
	}
	src, err := planguard.GenPolicy(c, planpolicy.Legacy)
	if err != nil {
		t.Fatal(err)
	}
	want, err := os.ReadFile("../../db/planpolicy/cached_gen.go")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(src, want) {
		t.Errorf("db/planpolicy/cached_gen.go is stale; run go run ./cmd/planguard gen-policy. Generated:\n%s", src)
	}
	got := slices.Sorted(maps.Keys(planpolicy.Cached))
	if !slices.Equal(got, []string{"GetNodeByID", "ListKnownRoutesByIATA", "ListKnownRoutesGlobal"}) {
		t.Errorf("planpolicy.Cached = %v", got)
	}
	for _, line := range []string{
		"// Code generated by the plan policy generator. DO NOT EDIT.",
		"// Cached lists class G statements: those admitted to the generic-plan class.",
	} {
		if !bytes.Contains(src, []byte(line+"\n")) {
			t.Errorf("generated source lacks %q", line)
		}
	}
}
